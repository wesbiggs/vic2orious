// Port of vic2/build.py's convert_new (without the cache and the build's side files): one
// picture's palette indices converted at its place on the screen and packed as a .v2i
// (docs/v2i-format.md, version 6).

import * as timing from "./timing.js";
import { Converter, Geometry, resetCaches, blockOf, blockStart, PTR, ZERO_SLOT } from "./convert.js";
import { VERSION } from "./version.js";

export const V2I_VERSION = 6, V2I_LOAD = 0x2000, PLAYER_BUF = 0x2800, BANK = 3;
const V2I_META = 1, V2I_MC = 2, V2I_THUMB = 4, META_MAX = 1024;
const META_KEY_BY = ["quantized by", "quantiser"];
const BANK_TOP_SLOT = { 1: 127, 2: 63, 3: 127 };

/** $00,n = n zero bytes (1..255); other bytes literal; $00,$00 ends. */
export function rleZero(data) {
  const out = [];
  let i = 0;
  while (i < data.length) {
    if (data[i] === 0) {
      let n = 1;
      while (i + n < data.length && data[i + n] === 0 && n < 255) n++;
      out.push(0, n);
      i += n;
    } else out.push(data[i++]);
  }
  out.push(0, 0);
  return out;
}

const pad2 = (n) => String(n).padStart(2, "0");

/** build.v2i_metadata: settings (img2c64's text), the build's lines; ASCII bytes. */
export function metadata(settings, imageName, frame, date = new Date()) {
  const lines = settings.split(/\r\n|\r|\n/).filter((l) => l.includes(":")).map((l) => l.trim());
  let by = "unknown";
  for (const l of lines.filter((l) => META_KEY_BY.includes(l.split(":")[0]))) {
    by = l.slice(l.indexOf(":") + 1).trim();
    lines.splice(lines.indexOf(l), 1);
  }
  const stamp = `${date.getUTCFullYear()}-${pad2(date.getUTCMonth() + 1)}-${pad2(date.getUTCDate())} ` +
    `${pad2(date.getUTCHours())}:${pad2(date.getUTCMinutes())} UTC`;
  lines.unshift(`quantized by: ${by}`, `generated by: vic2orious@${VERSION}`, `date: ${stamp}`);
  const keys = new Set(lines.map((l) => l.split(":")[0]));
  lines.push(`image: ${imageName}`);
  if (!keys.has("palette")) lines.push("palette: unknown, mapped to nearest Pepto");
  lines.push(`frame: ${frame ? "yes" : "no"}`);
  const text = lines.map((l) => l + "\n").join("");
  const out = [];
  for (const ch of text) out.push(ch === "\n" || (ch >= " " && ch <= "~") ? ch.charCodeAt(0) : 0x3f);
  return out.slice(0, META_MAX);
}

/** build.place, for an image without text: centred, unframed. */
export function place(cols, rows) {
  return [Math.floor((40 - cols) / 2), Math.floor((25 - rows) / 2)];
}

const le16 = (v) => [v & 0xff, (v >> 8) & 0xff];

/** Convert rows (palette indices; multicolour: wide pixels) for system and pack them.
 * settings: img2c64's text; thumb: thumbnail bytes; imageName: the "image" line.
 * Returns {v2i (Uint8Array, with the load address), w, h, rendered, wrong, badLines,
 * size, topSlot, mc}. Throws if the result does not fit the players' buffer or the bank. */
export function convertImage(rows, system, { mc = false, settings = "", thumb, imageName = "picture.png", date, progress = null } = {}) {
  if (timing.STANDARD !== system) { timing.setStandard(system); resetCaches(); }
  const h = rows.length, w = rows[0].length, cw = mc ? 4 : 8;
  const [col0, row0] = place(w / cw, h / 8);
  const conv = new Converter(rows, { frame: false, at: [col0, row0], mc, progress });
  const g = conv.g;
  conv.run();
  const bits = conv.bitmap();
  const bmp = new Uint8Array(320 * g.rows), scr = new Uint8Array(40 * g.rows), col = new Uint8Array(40 * g.rows);
  for (let cy = 0; cy < g.rows; cy++) {
    for (let cx = 0; cx < g.cols; cx++) {
      const o = cy * 320 + (g.col0 + cx) * 8;
      for (let i = 0; i < 8; i++) {
        const y = cy * 8 + i;
        let b = 0;
        if (mc) for (let j = 0; j < 4; j++) b |= bits[y][cx * 4 + j] << (6 - 2 * j);
        else for (let j = 0; j < 8; j++) if (bits[y][cx * 8 + j]) b |= 0x80 >> j;
        bmp[o + i] = b;
      }
      if (mc) {
        const [c1, c2, c3] = conv.pairs[cy][cx];
        scr[cy * 40 + g.col0 + cx] = (c1 << 4) | c2;
        col[cy * 40 + g.col0 + cx] = c3;
      } else {
        const [fg, bg] = conv.pairs[cy][cx];
        scr[cy * 40 + g.col0 + cx] = (fg << 4) | bg;
      }
    }
  }
  const slots = new Map();
  for (let s = 0; s < 8; s++) {
    for (const [r, sbits] of conv.sdata[s]) {
      const k = blockOf(s, r);
      const slot = g.slotOf(s, k);
      if (slot === ZERO_SLOT) throw new Error("sprite data in the zero slot");
      const row = r - blockStart(s, k);
      if (!slots.has(slot)) slots.set(slot, new Uint8Array(64));
      slots.get(slot).set([(sbits >> 16) & 0xff, (sbits >> 8) & 0xff, sbits & 0xff], row * 3);
    }
  }
  const topSlot = slots.size ? Math.max(...slots.keys()) : ZERO_SLOT;
  if (topSlot > BANK_TOP_SLOT[BANK]) throw new Error(`needs sprite blocks up to ${topSlot}, more than bank ${BANK} has`);
  const nslots = slots.size ? topSlot - ZERO_SLOT + 1 : 1;
  const spr = new Uint8Array(64 * nslots);
  for (const [slot, blk] of slots) spr.set(blk, (slot - ZERO_SLOT) * 64);
  const code = conv.kernel.code;
  const reloc = timing.pointerHiOffsets(code, new Set(PTR));
  const kstream = [...le16(reloc.length), ...reloc.flatMap(le16), ...code];
  const packed = [kstream, rleZero(bmp), rleZero(scr), rleZero(spr)];
  const out = conv.render();
  let wrong = 0;
  const badLines = [];
  for (let y = 0; y < h; y++) {
    let bad = false;
    for (let x = 0; x < w; x++) if (out[y][x] !== rows[y][x]) { wrong++; bad = true; }
    if (bad) badLines.push(y);
  }
  const hdr = [0x56, 0x32, 0x49, V2I_VERSION, g.cols, g.rows, g.col0, g.row0];
  for (const v of [...packed.map((d) => d.length), 0x2000 + 320 * g.row0, 40 * g.row0, badLines.length, Math.min(wrong, 0xffff)]) hdr.push(...le16(v));
  hdr.push(timing.SYSTEM_ID[timing.STANDARD], V2I_META | V2I_THUMB | (mc ? V2I_MC : 0));
  if (mc) {
    const cram = rleZero(col);
    packed.push([conv.bg, ...le16(cram.length), ...cram]);
  }
  const meta = metadata(settings, imageName, false, date);
  hdr.push(...thumb, ...le16(meta.length), ...meta);
  const size = hdr.length + packed.reduce((n, d) => n + d.length, 0);
  if (size > 0x9800 - PLAYER_BUF) throw new Error(`.v2i too big for the players' buffer (${size} bytes)`);
  const v2i = new Uint8Array(2 + size);
  v2i.set(le16(V2I_LOAD), 0);
  let o = 2;
  for (const part of [hdr, ...packed]) { v2i.set(part, o); o += part.length; }
  return { v2i, w, h, rendered: out, wrong, badLines, size, topSlot, mc, geom: g };
}
