"""Writes web/js/prg-template.js: the dual v2i demo (asm/v2i-demo.s, DUAL=1, as vic2.prg
assembles it) without its two images, for the web tool to put its own after.

The demo's DATA segment holds only the two images (v2idemo.inc), so the PRG is the
assembled code followed by the PAL and the NTSC .v2i (without their load addresses).
The code refers to the NTSC image's address (lda #<demo_img_n / ldy #>demo_img_n), so
the template records where those two operands are. Found by assembling twice with images
of different sizes and comparing; checked by a third assembly.

    python3 web/tools/prg_template.py

Needs cc65 (cl65) and the C64 character ROM that the build reads its default font from
(VICE_DATA, see vic2/fonts.py), though the demo draws no text.
"""

import base64
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
sys.path.insert(0, ROOT)
from vic2 import build  # noqa: E402

OUT = os.path.join(HERE, "..", "js", "prg-template.js")


def assemble(pal, ntsc):
    """The dual demo PRG with these two images (bytes without a load address)."""
    d = tempfile.mkdtemp()
    for name, data in (("pal.v2i", pal), ("ntsc.v2i", ntsc)):
        with open(os.path.join(d, name), "wb") as f:
            f.write(b"\0\0" + data)
    with open(os.path.join(d, "v2idemo.inc"), "w") as f:
        f.write('        .data\ndemo_img: .incbin "pal.v2i", 2\n'
                'demo_img_n: .incbin "ntsc.v2i", 2\n')
    build.BUILD = d
    out = os.path.join(d, "demo.prg")
    build.assemble(out, "v2i-demo.s", defines=["DUAL=1"])
    with open(out, "rb") as f:
        return f.read()


def main():
    sizes = [(1000, 2000), (1301, 777), (4097, 3)]
    prgs = [assemble(bytes((i * 7 + 1) & 0xff for i in range(a)),
                     bytes((i * 5 + 3) & 0xff for i in range(b))) for a, b in sizes]
    a, b = sizes[0]
    code = prgs[0][:len(prgs[0]) - a - b]
    lens = {len(p) - x - y for p, (x, y) in zip(prgs, sizes)}
    assert lens == {len(code)}, "the code's length depends on the images"
    diff = [i for i in range(len(code)) if prgs[0][i] != prgs[1][i]]
    load = code[0] | code[1] << 8
    base = load + len(code) - 2          # address of the PAL image (after the load address)
    assert len(diff) == 2, "expected the two operands of the NTSC address to differ: %r" % diff
    lo, hi = diff
    for p, (x, y) in zip(prgs, sizes):
        n = base + x
        assert p[lo] == n & 0xff and p[hi] == n >> 8, "operands are not demo_img_n"
        assert p[2:lo] == code[2:lo] and p[lo + 1:hi] == code[lo + 1:hi]
    with open(OUT, "w") as f:
        f.write("// Generated by web/tools/prg_template.py from asm/v2i-demo.s (DUAL=1, "
                "V2I_BANK=%d): the dual\n// demo's code; the PAL and NTSC .v2i follow it "
                "(without load addresses), and the code's\n// operands at NTSC_LO and NTSC_HI "
                "take the NTSC image's address.\n" % build.BANK)
        f.write("export const CODE = \"%s\";\n" % base64.b64encode(code).decode())
        f.write("export const NTSC_LO = %d, NTSC_HI = %d;\n" % (lo, hi))
    print("%s: %d bytes of code (load $%04x, PAL image at $%04x), NTSC address at %d, %d"
          % (OUT, len(code), load, base, lo, hi))


if __name__ == "__main__":
    main()
