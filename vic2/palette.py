def _known():
    """Exact colour -> index for every palette above (nearest() alone gets VICE's bright
    colours wrong: its red is nearer Pepto light red)."""
    known = {}
    for pal in (PEPTO, COLODORE, COLODORE_VICE_PAL, COLODORE_VICE_NTSC):
        for i, c in enumerate(pal):
            assert known.setdefault(c, i) == i, "colour %r in two places" % (c,)
    return known


KNOWN = _known()


def nearest(rgb, palette=PEPTO):
    r, g, b = rgb[:3]
    return min(range(len(palette)),
               key=lambda i: (palette[i][0] - r) ** 2 + (palette[i][1] - g) ** 2 + (palette[i][2] - b) ** 2)


def load_indexed(path, palette=PEPTO):
    """Load an image and map every pixel to a palette index; returns (w, h, rows). With
    PEPTO, colours of the known palettes (KNOWN) map exactly, others to the nearest."""
    im = Image.open(path).convert("RGB")
    w, h = im.size
    px = im.load()
    cache = dict(KNOWN) if palette is PEPTO else {}
    rows = []
    for y in range(h):
        row = []
        for x in range(w):
            c = px[x, y]
            if c not in cache:
                cache[c] = nearest(c, palette)
            row.append(cache[c])
        rows.append(row)
    return w, h, rows


def save_indexed(path, rows, palette=PEPTO, scale=1):
    h = len(rows)
    w = len(rows[0])
    im = Image.new("RGB", (w, h))
    im.putdata([palette[c] for row in rows for c in row])
    if scale != 1:
        im = im.resize((w * scale, h * scale), Image.NEAREST)
    im.save(path)


def load_vpl(path):
    pal = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            pal.append(tuple(int(p, 16) for p in parts[:3]))
    return pal[:16]
